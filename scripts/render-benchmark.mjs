#!/usr/bin/env node
// Renders docs/benchmark-results.md from docs/benchmark-results.json.
//
// Kept separate so the published table is always a projection of a measurement
// rather than something a person typed.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const results = JSON.parse(await readFile(join(REPO, 'docs', 'benchmark-results.json'), 'utf8'));
const { benchmark: b, discovery, evals, run, ask, environment } = results;

const range = (spread) => (spread && spread.samples > 1 ? ` (${spread.min}–${spread.max})` : '');
const tokens = (value) => (value === 'unavailable' ? '*unavailable*' : String(value));

const lines = [
  '# Measured results',
  '',
  '<!-- Generated by `node scripts/measure-demo.mjs`. Do not edit by hand. -->',
  '',
  `Measured on ${results.generatedAt} · Node ${environment.node} · ${environment.platform}`,
  `Target: ${results.target}`,
  '',
  '## Browser vs GhostAPI',
  '',
  `${b.runs} timed run(s) per path, after one untimed warm-up. Figures are medians; the range follows in brackets.`,
  '',
  '| | browser (recorded UI replay) | ghostapi (direct API) |',
  '| --- | ---: | ---: |',
  `| median time | ${b.browserMs} ms${range(b.browserSpreadMs)} | **${b.apiMs} ms${range(b.apiSpreadMs)}** |`,
  `| interactions | ${b.browserInteractions} | 0 |`,
  `| requests | ${b.browserRequests} | ${b.apiRequests} |`,
  `| model calls | 0 | ${b.apiModelCalls} |`,
  `| tokens | ${tokens(b.browserTokens)} | ${tokens(b.apiTokens)} |`,
  '',
  `**${b.speedup}× faster through the discovered API.**`,
  '',
  ...b.notes.map((note) => `> ${note}`),
  '',
  '## Discovery',
  '',
  `| candidate endpoint groups | ${discovery.candidateGroups} |`,
  '| --- | ---: |',
  `| operations derived | ${discovery.operations} |`,
  `| createTodo confidence | ${Math.round(discovery.createTodoConfidence * 100)}% |`,
  `| createTodo observations | ${discovery.createTodoObservations} |`,
  '',
  `Operations: ${discovery.operationNames.map((name) => `\`${name}\``).join(', ')}`,
  '',
  `Inferred inputs for \`createTodo\`: ${discovery.createTodoInputs.map((name) => `\`${name}\``).join(', ')}`,
  '',
  '## Single executions',
  '',
  `| \`ghostapi run createTodo\` | ${run.transport} · ${run.status} · ${run.latencyMs} ms |`,
  '| --- | --- |',
  `| \`ghostapi ask "create a todo called buy coffee"\` | ${ask.engine} → \`${ask.operation}\` at ${(ask.confidence * 100).toFixed(1)}% · ${ask.status} · ${ask.latencyMs} ms |`,
  '',
  '## Evals',
  '',
  `${evals.passed} passed, ${evals.failed} failed, ${evals.skipped} skipped across ${evals.cases} cases and ${evals.operations} operations.`,
  '',
  `Reliability over the cases that ran: **${evals.reliabilityPercent}%**.`,
  '',
];

const file = join(REPO, 'docs', 'benchmark-results.md');
await writeFile(file, `${lines.join('\n')}\n`, 'utf8');
process.stdout.write(`${file}\n`);
